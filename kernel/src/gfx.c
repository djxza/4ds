// Draw a single character
void draw_char(int x, int y, char c, u32 color, u32 *pixels) {
  if (c < 32 || c > 127)
    return; // Only printable ASCII

  const u8 *glyph = font_8x8[c - 32];

  for (int row = 0; row < 8; row++) {
    u8 row_data = glyph[row];
    for (int col = 0; col < 8; col++) {
      if (row_data & (1 << (7 - col))) {
        putpixel(x + col, y + row, color, pixels);
      }
    }
  }
}

// Draw text string
void draw_text(int x, int y, const char *text, u32 color, u32 shadow_color,
               u32 *pixels) {
  int start_x = x;

  while (*text) {
    // Draw shadow (offset by 1 pixel)
    if (shadow_color != 0) {
      draw_char(start_x + 1, y + 1, *text, shadow_color, pixels);
    }

    // Draw main character
    draw_char(start_x, y, *text, color, pixels);

    start_x += 9; // 8 pixels width + 1 pixel spacing
    text++;
  }
}
