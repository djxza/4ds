#include "gfx.h"

__attribute__((used)) volatile struct limine_framebuffer_request fb_request = {
    .id = LIMINE_FRAMEBUFFER_REQUEST_ID, .revision = 0};

screen_t _screen;
struct limine_framebuffer *fb = NULL;

void initscr() {
  ASSERT(fb_request.response && fb_request.response->framebuffers > 0);
  fb = fb_request.response->framebuffers[0];

  _screen.pixels = (u32 *)fb->address;
  _screen.width = fb->width;
  _screen.height = fb->height;
  _screen.pitch = fb->pitch / 4;
}

screen_t get_screen() { return _screen; }

void putpixel(int x, int y, u32 col, u32 *pixels) {
  if ((unsigned)x >= (unsigned)_screen.width ||
      (unsigned)y >= (unsigned)_screen.height)
    return;

  pixels[y * _screen.pitch + x] = col;
}

u32 lerp_color(u32 a, u32 b, int t, int max) {
  int ar = (a >> 16) & 255;
  int ag = (a >> 8) & 255;
  int ab = (a) & 255;

  int br = (b >> 16) & 255;
  int bg = (b >> 8) & 255;
  int bb = (b) & 255;

  int r = ar + (br - ar) * t / max;
  int g = ag + (bg - ag) * t / max;
  int b2 = ab + (bb - ab) * t / max;

  return (r << 16) | (g << 8) | b2;
}

void fill_rect(int x, int y, int w, int h, u32 col, u32 *pixels) {
  if (w <= 0 || h <= 0)
    return;

  for (int yy = 0; yy < h; yy++) {
    u32 *row = &pixels[(y + yy) * _screen.pitch + x];
    for (int xx = 0; xx < w; xx++)
      row[xx] = col;
  }
}

// Draw anti-aliased circle for better rounded corners
void draw_circle(int cx, int cy, int radius, u32 color, u32 *pixels) {
  int r2 = radius * radius;
  for (int y = -radius; y <= radius; y++) {
    for (int x = -radius; x <= radius; x++) {
      if (x * x + y * y <= r2) {
        putpixel(cx + x, cy + y, color, pixels);
      }
    }
  }
}

// Rounded rectangle with proper anti-aliasing
void fill_rounded_rect(int x, int y, int w, int h, int radius, u32 col,
                       u32 *pixels) {
  // Fill center
  fill_rect(x + radius, y, w - 2 * radius, h, col, pixels);
  fill_rect(x, y + radius, w, h - 2 * radius, col, pixels);

  // Draw corners
  for (int i = 0; i <= radius; i++) {
    for (int j = 0; j <= radius; j++) {
      if (i * i + j * j <= radius * radius) {
        putpixel(x + i, y + j, col, pixels);
        putpixel(x + w - 1 - i, y + j, col, pixels);
        putpixel(x + i, y + h - 1 - j, col, pixels);
        putpixel(x + w - 1 - i, y + h - 1 - j, col, pixels);
      }
    }
  }
}

